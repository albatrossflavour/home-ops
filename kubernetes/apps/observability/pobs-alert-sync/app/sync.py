"""Propose the Puppet Observability alert rules to home-ops as a pull request.

Fetches the PrometheusRule the POBS daemon composes for this estate (R1168),
validates it with promtool, and compares it with what main carries. If it
differs, it force-resets BRANCH to main, commits the new file there and opens
or updates one PR. The PR is the gate: nothing here touches the cluster, and
Flux reconciles on merge.

Stdlib only, so the image needs nothing installed.
"""
import base64
import json
import os
import re
import ssl
import subprocess
import sys
import urllib.error
import urllib.parse
import urllib.request

ENDPOINT = os.environ.get("POBS_ENDPOINT", "https://puppet.lab.albatrossflavour.com:10051/api/v1/alerts/prometheusrule")
LABELS = os.environ.get("POBS_LABELS", "prometheus=kube-prometheus,role=alert-rules")
TLS_DIR = os.environ.get("TLS_DIR", "/tls")
PROMTOOL = os.environ.get("PROMTOOL", "/tools/promtool")
REPO = os.environ.get("REPO", "albatrossflavour/home-ops")
TARGET = os.environ.get("TARGET_PATH", "kubernetes/apps/observability/custom-alerts/app/puppet.yaml")
BRANCH = os.environ.get("BRANCH", "pobs/alert-rules")
DRY_RUN = os.environ.get("DRY_RUN") == "1"


def fetch_rules():
    # RULES_FILE lets the script run against a saved render without the cert.
    if os.environ.get("RULES_FILE"):
        with open(os.environ["RULES_FILE"], "rb") as f:
            return f.read()
    ctx = ssl.create_default_context(cafile=f"{TLS_DIR}/ca.crt")
    ctx.load_cert_chain(f"{TLS_DIR}/tls.crt", f"{TLS_DIR}/tls.key")
    url = f"{ENDPOINT}?{urllib.parse.urlencode({'labels': LABELS})}"
    with urllib.request.urlopen(url, context=ctx, timeout=60) as r:
        return r.read()


def rules_document(prometheusrule):
    """The rule groups as a plain rules file promtool accepts.

    The writer emits `spec:` at column 0 with everything under it indented two
    spaces, so dropping the envelope is a dedent, not a YAML parse.
    """
    lines = prometheusrule.decode().splitlines()
    start = lines.index("spec:") + 1
    body = lines[start:]
    assert all(not l or l.startswith("  ") for l in body), "unexpected layout under spec:"
    return "\n".join(l[2:] for l in body) + "\n"


def validate(prometheusrule):
    with open("/tmp/rules.yaml", "w") as f:
        f.write(rules_document(prometheusrule))
    subprocess.run([PROMTOOL, "check", "rules", "/tmp/rules.yaml"], check=True)


def gh(method, path, body=None):
    req = urllib.request.Request(
        f"https://api.github.com/repos/{REPO}{path}",
        method=method,
        data=json.dumps(body).encode() if body is not None else None,
        headers={
            "Authorization": f"Bearer {os.environ['GITHUB_TOKEN']}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            return json.load(r)
    except urllib.error.HTTPError as e:
        # GitHub's reason ("Resource not accessible by personal access token")
        # is in the body, and a bare 403 says nothing about which permission.
        print(f"{method} {path}: {e.code} {e.read().decode(errors='replace')}", file=sys.stderr)
        raise


def summary(text):
    t = text.decode()
    version = re.search(r"pobs\.puppet\.com/module-version: *(\S+)", t)
    return {
        "version": version.group(1) if version else "unknown",
        "alerts": set(re.findall(r"^ *- alert: *(\S+)", t, re.M)),
        "records": len(re.findall(r"^ *- record:", t, re.M)),
    }


def pr_body(old, new):
    added = sorted(new["alerts"] - old["alerts"])
    removed = sorted(old["alerts"] - new["alerts"])
    delta = [f"+ {a}" for a in added] + [f"- {a}" for a in removed]
    return "\n".join([
        "Generated by `GET /api/v1/alerts/prometheusrule` on the POBS primary, at this estate's thresholds.",
        "",
        "| | in cluster | proposed |",
        "| --- | --- | --- |",
        f"| module version | {old['version']} | {new['version']} |",
        f"| alerting rules | {len(old['alerts'])} | {len(new['alerts'])} |",
        f"| recording rules | {old['records']} | {new['records']} |",
        "",
        "### Alerts",
        "```diff\n" + "\n".join(delta) + "\n```" if delta
        else "No alerts added or removed: expressions, thresholds or the version annotation moved.",
        "",
        "`promtool check rules` passed before this was proposed. Merging it lets Flux reconcile.",
        "",
        "Opened by the `pobs-alert-sync` CronJob in `observability`.",
    ])


def main():
    rendered = fetch_rules()
    validate(rendered)

    current = gh("GET", f"/contents/{TARGET}?ref=main")
    current_bytes = base64.b64decode(current["content"])
    if current_bytes == rendered:
        print("Rule set is identical to what main carries. Nothing to propose.")
        return

    old, new = summary(current_bytes), summary(rendered)
    title = f"chore(observability): regenerate pobs alert rules ({old['version']} -> {new['version']})"
    body = pr_body(old, new)
    print(title)
    print(body)
    if DRY_RUN:
        return

    # Each run builds one commit on top of main (the file is a whole artefact)
    # and moves the branch straight to it. Resetting the branch to main first
    # makes the open PR empty for a moment, and GitHub closes an empty PR.
    main_sha = gh("GET", "/git/ref/heads/main")["object"]["sha"]
    base_tree = gh("GET", f"/git/commits/{main_sha}")["tree"]["sha"]
    tree = gh("POST", "/git/trees", {
        "base_tree": base_tree,
        "tree": [{"path": TARGET, "mode": "100644", "type": "blob", "content": rendered.decode()}],
    })["sha"]
    commit = gh("POST", "/git/commits", {"message": title, "tree": tree, "parents": [main_sha]})["sha"]
    try:
        gh("PATCH", f"/git/refs/heads/{BRANCH}", {"sha": commit, "force": True})
    except urllib.error.HTTPError as e:
        if e.code not in (404, 422):
            raise
        gh("POST", "/git/refs", {"ref": f"refs/heads/{BRANCH}", "sha": commit})

    owner = REPO.split("/")[0]
    open_prs = gh("GET", f"/pulls?state=open&head={owner}:{BRANCH}")
    if open_prs:
        number = open_prs[0]["number"]
        gh("PATCH", f"/pulls/{number}", {"title": title, "body": body})
    else:
        number = gh("POST", "/pulls", {"title": title, "head": BRANCH, "base": "main", "body": body})["number"]

    # This job exists to stop the rules drifting quietly, so it must not
    # propose nothing and report success.
    if not gh("GET", f"/pulls?state=open&head={owner}:{BRANCH}"):
        sys.exit(f"Rules differ but no open pull request exists on {BRANCH}.")
    print(f"Proposed on #{number}.")


if __name__ == "__main__":
    main()
